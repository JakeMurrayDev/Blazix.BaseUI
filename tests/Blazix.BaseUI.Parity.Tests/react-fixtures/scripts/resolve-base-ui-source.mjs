import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

function locateBaseUi() {
  const override = process.env.PARITY_BASE_UI_PATH;
  if (override) {
    if (!existsSync(override)) {
      throw new Error(`PARITY_BASE_UI_PATH points at a missing directory: ${override}`);
    }
    return override;
  }

  // Walk up from this script looking for a sibling `.base-ui` checkout. In a git
  // worktree the checkout lives at the MAIN repo root, several levels above.
  let dir = here;
  for (let i = 0; i < 12; i++) {
    const candidate = join(dir, '.base-ui');
    if (existsSync(join(candidate, 'packages/react'))) {
      return candidate;
    }
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }

  throw new Error(
    'Could not locate the .base-ui checkout. Set PARITY_BASE_UI_PATH to its absolute path.',
  );
}

const baseUi = locateBaseUi();
const demos = resolve(baseUi, 'docs/src/app/(docs)/react/components');

// Validate the path actually emitted, not just the checkout root. Without this,
// a PARITY_BASE_UI_PATH override aimed at any existing directory — or an upstream
// move of the docs route — emits an @source pointing at nothing. Tailwind then
// silently omits every React-demo utility, both sides fall back to browser
// defaults identically, and fixtures pass while testing nothing.
if (!existsSync(demos)) {
  throw new Error(
    `base-ui checkout at ${baseUi} has no demo directory at ${demos}. ` +
      'Check PARITY_BASE_UI_PATH, or the upstream docs layout may have moved.',
  );
}

writeFileSync(
  join(here, '..', 'src', 'base-ui-source.css'),
  `/* generated by scripts/resolve-base-ui-source.mjs — do not edit */\n@source "${demos}";\n`,
);

console.log(`[parity] base-ui: ${baseUi}`);
